"""Balance sweep: scripted human vs scripted zombies over zombie and food counts.

Writes a Markdown report and the raw JSON results. Example:

    python -m arena.balance_sweep --zombies 5,10,20,35,50 --food 20,40,80,120 --episodes 64
"""

import argparse
import json
import time
from pathlib import Path

from zai_env.config import load_config
from zai_rl.bots import ScriptedHuman, ScriptedZombies

from .matches import play


def _ints(text: str) -> list[int]:
    return [int(v) for v in text.split(",") if v]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=None, help="base environment YAML")
    parser.add_argument("--zombies", type=_ints, default=_ints("5,10,20,35,50"))
    parser.add_argument("--food", type=_ints, default=_ints("20,40,80,120"))
    parser.add_argument(
        "--respawn", type=float, default=60.0, help="food respawn interval in s (<0 disables)"
    )
    parser.add_argument("--episodes", type=int, default=64, help="episodes per cell")
    parser.add_argument("--reserve", type=int, default=2, help="scripted human food reserve")
    parser.add_argument("--human-fov", type=float, default=None, help="human field of view (deg)")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--threads", type=int, default=None)
    parser.add_argument("--out", type=Path, default=Path("docs/reports/balance_sweep"))
    args = parser.parse_args()

    respawn = None if args.respawn < 0 else args.respawn
    results = []
    started = time.time()
    for zombies in args.zombies:
        for food in args.food:
            config = load_config(
                args.config,
                overrides={
                    "zombie_count": zombies,
                    "food_count": food,
                    "food_respawn_interval_s": respawn,
                    **({"human": {"vision_fov_deg": args.human_fov}} if args.human_fov else {}),
                },
                env_overrides=False,
            )
            stats = play(
                config,
                lambda c, e, s: ScriptedHuman(c, e, seed=s, reserve=args.reserve),
                lambda c, e, n, s: ScriptedZombies(c, e, n, seed=s),
                episodes=args.episodes,
                seed=args.seed,
                num_threads=args.threads,
            )
            results.append({"zombies": zombies, "food": food, **stats.as_dict()})
            print(
                f"zombies {zombies:3d} food {food:4d}: caught {stats.caught:6.1%} "
                f"starved {stats.starved:6.1%} survived {stats.survived:6.1%} "
                f"mean {stats.mean_length_s:7.1f} s",
                flush=True,
            )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    meta = {
        "episodes_per_cell": args.episodes,
        "food_respawn_interval_s": respawn,
        "seed": args.seed,
        "human_reserve": args.reserve,
        "zombie_speed_mps": config["zombie"]["speed_mps"],
        "human_fov_deg": config["human"]["vision_fov_deg"],
        "base_config": str(args.config) if args.config else "defaults",
        "elapsed_s": round(time.time() - started, 1),
    }
    args.out.with_suffix(".json").write_text(
        json.dumps({"meta": meta, "results": results}, indent=2)
    )
    args.out.with_suffix(".md").write_text(_markdown(meta, results, args.zombies, args.food))
    print(f"wrote {args.out.with_suffix('.md')} and {args.out.with_suffix('.json')}")


def _markdown(meta: dict, results: list[dict], zombies: list[int], food: list[int]) -> str:
    by_key = {(r["zombies"], r["food"]): r for r in results}

    def table(title: str, cell) -> list[str]:
        lines = [f"### {title}", "", "| zombies \\ food | " + " | ".join(map(str, food)) + " |"]
        lines.append("|---" * (len(food) + 1) + "|")
        for z in zombies:
            lines.append(f"| {z} | " + " | ".join(cell(by_key[(z, f)]) for f in food) + " |")
        return lines + [""]

    lines = [
        "# Balance sweep: scripted human vs scripted zombies",
        "",
        f"- Episodes per cell: {meta['episodes_per_cell']}; seed {meta['seed']}; "
        f"base config: {meta['base_config']}",
        f"- Food respawn interval: {meta['food_respawn_interval_s']} s",
        f"- Zombie speed: {meta['zombie_speed_mps']} m/s; scripted human food reserve: "
        f"{meta['human_reserve']}",
        f"- Human field of view: {meta['human_fov_deg']} degrees",
        f"- Generated by `python -m arena.balance_sweep` in {meta['elapsed_s']} s",
        "",
    ]
    lines += table("Caught (zombie win)", lambda r: f"{r['caught']:.0%}")
    lines += table("Survived the cap (human win)", lambda r: f"{r['survived']:.0%}")
    lines += table("Starved (draw)", lambda r: f"{r['starved']:.0%}")
    lines += table("Mean episode length (s)", lambda r: f"{r['mean_length_s']:.0f}")
    return "\n".join(lines)


if __name__ == "__main__":
    main()
