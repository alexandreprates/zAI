//! Replays: `(config, seed, action log)` per episode, re-simulated deterministically.

use std::collections::HashSet;
use std::path::PathBuf;
use std::sync::{Arc, Mutex};

use serde::{Deserialize, Serialize};
use zai_sim::{Config, Env, HumanAction};

use crate::matches::Agent;

/// Who played one side of a replayed episode: a server bot, or a trained policy (live server
/// matches, or episodes recorded offline by `python -m arena.export_replays`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ReplayAgent {
    Scripted,
    Random,
    Policy,
}

impl From<&Agent> for ReplayAgent {
    fn from(agent: &Agent) -> Self {
        match agent {
            Agent::Scripted => Self::Scripted,
            Agent::Random => Self::Random,
            Agent::Policy(_) => Self::Policy,
        }
    }
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Replay {
    pub id: String,
    pub match_id: String,
    pub episode: u32,
    pub created_at: u64,
    pub config: Config,
    pub seed: u64,
    pub human: ReplayAgent,
    pub zombies: ReplayAgent,
    /// Model ids of policy sides played on the server (`policy.rs`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub human_model: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub zombie_model: Option<String>,
    /// One entry per decision step: `[movement, interact, zombie_0, .., zombie_{N-1}]`.
    pub actions: Vec<Vec<u8>>,
    pub outcome: String,
    /// `Env::state_hash()` after the last step, as hex (u64 does not fit a JSON number in JS).
    pub final_hash: String,
}

#[derive(Clone, Debug, Serialize)]
pub struct ReplaySummary {
    pub id: String,
    pub match_id: String,
    pub episode: u32,
    pub created_at: u64,
    pub seed: u64,
    pub human: ReplayAgent,
    pub zombies: ReplayAgent,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub human_model: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub zombie_model: Option<String>,
    pub outcome: String,
    pub length: usize,
}

impl Replay {
    pub fn summary(&self) -> ReplaySummary {
        ReplaySummary {
            id: self.id.clone(),
            match_id: self.match_id.clone(),
            episode: self.episode,
            created_at: self.created_at,
            seed: self.seed,
            human: self.human,
            zombies: self.zombies,
            human_model: self.human_model.clone(),
            zombie_model: self.zombie_model.clone(),
            outcome: self.outcome.clone(),
            length: self.actions.len(),
        }
    }

    pub fn encode_step(human: HumanAction, zombies: &[u8]) -> Vec<u8> {
        let mut v = Vec::with_capacity(2 + zombies.len());
        v.push(human.movement);
        v.push(human.interact);
        v.extend_from_slice(zombies);
        v
    }

    /// Applies decision step `tick` of the log to `env`.
    pub fn apply(&self, env: &mut Env, tick: usize) {
        let a = &self.actions[tick];
        env.step(
            HumanAction {
                movement: a[0],
                interact: a[1],
            },
            &a[2..],
        );
    }

    /// Environment state after the first `ticks` decision steps.
    pub fn simulate(&self, ticks: usize) -> Env {
        let mut env = Env::new(self.config.clone(), self.seed).expect("replay config is valid");
        for t in 0..ticks.min(self.actions.len()) {
            self.apply(&mut env, t);
        }
        env
    }

    /// True if re-simulating the whole log reproduces the recorded final state.
    pub fn verify(&self) -> bool {
        format!("{:016x}", self.simulate(self.actions.len()).state_hash()) == self.final_hash
    }
}

/// Replays stored as JSON files under a directory.
#[derive(Clone, Debug)]
pub struct ReplayStore {
    dir: PathBuf,
    /// Files already reported as unreadable (the viewer lists replays every few seconds).
    warned: Arc<Mutex<HashSet<PathBuf>>>,
}

/// Replay ids are generated by the server; reject anything else to keep paths safe.
pub fn valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 64
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

impl ReplayStore {
    pub fn new(dir: PathBuf) -> std::io::Result<Self> {
        std::fs::create_dir_all(&dir)?;
        Ok(Self {
            dir,
            warned: Arc::default(),
        })
    }

    fn path(&self, id: &str) -> Option<PathBuf> {
        valid_id(id).then(|| self.dir.join(format!("{id}.json")))
    }

    pub fn save(&self, replay: &Replay) -> std::io::Result<()> {
        let path = self
            .path(&replay.id)
            .ok_or_else(|| std::io::Error::other("invalid replay id"))?;
        let tmp = path.with_extension("json.tmp");
        std::fs::write(&tmp, serde_json::to_vec(replay)?)?;
        std::fs::rename(tmp, path)
    }

    pub fn load(&self, id: &str) -> Option<Replay> {
        let bytes = std::fs::read(self.path(id)?).ok()?;
        serde_json::from_slice(&bytes).ok()
    }

    /// Summaries of every stored replay, newest first.
    pub fn list(&self) -> Vec<ReplaySummary> {
        let mut out: Vec<ReplaySummary> = std::fs::read_dir(&self.dir)
            .into_iter()
            .flatten()
            .flatten()
            .filter(|e| e.path().extension().is_some_and(|x| x == "json"))
            .filter_map(|e| {
                let path = e.path();
                let bytes = std::fs::read(&path).ok()?;
                serde_json::from_slice::<Replay>(&bytes)
                    .inspect_err(|err| {
                        if self
                            .warned
                            .lock()
                            .expect("warned lock")
                            .insert(path.clone())
                        {
                            tracing::warn!("skipping replay {}: {err}", path.display());
                        }
                    })
                    .ok()
            })
            .map(|r| r.summary())
            .collect();
        out.sort_by(|a, b| b.created_at.cmp(&a.created_at).then(b.id.cmp(&a.id)));
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use zai_sim::bots::{BotKind, HumanBot, ZombieBot};
    use zai_sim::Outcome;

    pub(crate) fn record(cfg: Config, seed: u64) -> Replay {
        let mut env = Env::new(cfg.clone(), seed).unwrap();
        let mut h = HumanBot::new(BotKind::Scripted, 1);
        let mut z = ZombieBot::new(BotKind::Scripted, 2);
        let mut actions = Vec::new();
        while env.outcome() == Outcome::Running {
            let a = h.act(&env);
            let za = z.act(&env);
            actions.push(Replay::encode_step(a, &za));
            env.step(a, &za);
        }
        Replay {
            id: "test-e0".into(),
            match_id: "test".into(),
            episode: 0,
            created_at: 0,
            config: cfg,
            seed,
            human: ReplayAgent::Scripted,
            zombies: ReplayAgent::Scripted,
            human_model: None,
            zombie_model: None,
            actions,
            outcome: crate::frames::outcome_name(env.outcome()).into(),
            final_hash: format!("{:016x}", env.state_hash()),
        }
    }

    #[test]
    fn replays_re_simulate_to_the_recorded_state_and_round_trip_on_disk() {
        let cfg = Config {
            episode_cap_s: 60.0,
            ..Config::default()
        };
        let replay = record(cfg, 9);
        assert_eq!(replay.actions.len(), 120);
        assert!(replay.verify());

        let dir = tempfile::tempdir().unwrap();
        let store = ReplayStore::new(dir.path().to_path_buf()).unwrap();
        store.save(&replay).unwrap();
        let loaded = store.load("test-e0").unwrap();
        assert!(loaded.verify());
        assert_eq!(store.list().len(), 1);
        assert!(store.load("../etc/passwd").is_none());
    }

    #[test]
    fn replays_recorded_by_a_policy_deserialize() {
        let mut replay = record(
            Config {
                episode_cap_s: 10.0,
                ..Config::default()
            },
            3,
        );
        replay.human = ReplayAgent::Policy;
        let json = serde_json::to_value(&replay).unwrap();
        assert_eq!(json["human"], "policy");
        let back: Replay = serde_json::from_value(json).unwrap();
        assert_eq!(back.human, ReplayAgent::Policy);
        assert!(back.verify());
    }
}
